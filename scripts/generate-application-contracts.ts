import {
  applicationSchema,
  definitions,
  operationCatalog,
  type Schema,
} from "../packages/application/src/schema.ts";
import { agentKitOutputs } from "./agent-kit.ts";
import { frozenContractProblems } from "./contract-freeze.ts";
import { mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const name = (value: string) =>
  value
    .replace(/(^|\.)([a-z])/g, (_, _prefix, letter: string) => letter.toUpperCase())
    .replace(/Id$/, "ID")
    .replace(/^Id$/, "ID");
function goType(schema: Schema): string {
  if (schema.$ref) return schema.$ref.slice("#/$defs/".length);
  if (schema.anyOf) {
    const other = schema.anyOf.filter((item) => item.type !== "null");
    if (other.length !== 1 || !other[0])
      throw new Error("Only nullable unions are supported by Go bindings");
    return `*${goType(other[0])}`;
  }
  switch (schema.type) {
    case "string":
      return "string";
    case "integer":
      return "int";
    case "boolean":
      return "bool";
    case "array":
      if (!schema.items) throw new Error("Array items required");
      return `[]${goType(schema.items)}`;
    case "object":
      if (!schema.properties) return "json.RawMessage";
      throw new Error("Use named object definitions");
    default:
      return "json.RawMessage";
  }
}
const header =
  '// Code generated by scripts/generate-application-contracts.ts; DO NOT EDIT.\n\npackage api\n\nimport (\n\t"context"\n\t"encoding/json"\n)\n\n';
function tsType(schema: Schema): string {
  if (schema.$ref) return schema.$ref.slice("#/$defs/".length);
  if (schema.anyOf) return schema.anyOf.map(tsType).join(" | ");
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  switch (schema.type) {
    case "string":
      return "string";
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      if (!schema.items) throw new Error("Array items required");
      return `readonly (${tsType(schema.items)})[]`;
    case "object": {
      if (!schema.properties) return "Readonly<Record<string, unknown>>";
      if (Object.keys(schema.properties).length === 0) return "Readonly<Record<string, never>>";
      return `{${Object.entries(schema.properties)
        .map(
          ([key, value]) =>
            `readonly ${JSON.stringify(key)}${schema.required?.includes(key) ? "" : "?"}: ${tsType(value)};`,
        )
        .join("\n")}}`;
    }
    default:
      return "unknown";
  }
}
let typescript = "// Generated by scripts/generate-application-contracts.ts; DO NOT EDIT.\n";
typescript += `export const API_VERSION = ${JSON.stringify(applicationSchema.version)} as const;\n`;
for (const [key, schema] of Object.entries(definitions))
  typescript += `export type ${key} = ${tsType(schema)};\n`;
for (const [map, side] of [
  ["ApplicationInputs", "input"],
  ["ApplicationOutputs", "output"],
] as const)
  typescript += `export interface ${map} { ${operationCatalog.map((operation) => `readonly ${JSON.stringify(operation.name)}: ${tsType(operation[side])};`).join("\n")} }\n`;
typescript += `export const WRITE_OPERATIONS = ${JSON.stringify(operationCatalog.filter((operation) => operation.writes).map((operation) => operation.name))} as const;\n`;
typescript += `export type ApplicationOperation = keyof ApplicationInputs;\nexport interface ApplicationRequest<K extends ApplicationOperation> { readonly version: typeof API_VERSION; readonly bookId: string; readonly operationId?: string; readonly input: ApplicationInputs[K]; }\n`;
typescript +=
  "export interface ApplicationFailure { readonly code: string; readonly message: string; readonly details: readonly { readonly path: string; readonly message: string }[]; readonly retryable: boolean; }\n";
typescript +=
  "export type ApplicationResponse<K extends ApplicationOperation> = { readonly version: typeof API_VERSION; readonly bookId: string; readonly operationId?: string; readonly ok: true; readonly data: ApplicationOutputs[K]; } | { readonly version: typeof API_VERSION; readonly bookId: string; readonly operationId?: string; readonly ok: false; readonly error: ApplicationFailure; };\n";
const tsFormatted = Bun.spawnSync(
  [
    resolve(root, "node_modules/.bin/biome"),
    "format",
    "--stdin-file-path=packages/application/src/client-contracts.gen.ts",
  ],
  { stdin: Buffer.from(typescript), stdout: "pipe", stderr: "pipe" },
);
if (tsFormatted.exitCode !== 0) throw new Error(new TextDecoder().decode(tsFormatted.stderr));
let source = `${header}const Version = ${JSON.stringify(applicationSchema.version)}\n\n`;
for (const [key, schema] of Object.entries(definitions)) {
  if (schema.type !== "object" || !schema.properties) {
    source += `type ${key} = ${goType(schema)}\n\n`;
    continue;
  }
  source += `type ${key} struct {\n`;
  for (const [field, child] of Object.entries(schema.properties)) {
    const optional = !schema.required?.includes(field);
    const type = goType(child);
    source += `\t${name(field)} ${optional && !type.startsWith("*") && type !== "json.RawMessage" ? "*" : ""}${type} \x60json:"${field}${optional ? ",omitempty" : ""}"\x60\n`;
  }
  source += "}\n\n";
}
for (const operation of operationCatalog) {
  source += `func (c *Client) ${name(operation.name)}(ctx context.Context, input ${goType(operation.input)}, operationID string) (${goType(operation.output)}, error) {\n\treturn typedCall[${goType(operation.output)}](ctx, c, ${JSON.stringify(operation.name)}, input, operationID)\n}\n\n`;
}
// gofmt is deterministic. No external generators or TypeScript UI compiler are
// involved; each binding follows the same language-neutral schema.
const formatted = Bun.spawnSync([process.env.GOFMT_BIN ?? "gofmt"], {
  stdin: Buffer.from(source),
  stdout: "pipe",
  stderr: "pipe",
});
if (formatted.exitCode !== 0) throw new Error(new TextDecoder().decode(formatted.stderr));
const json = `${JSON.stringify(applicationSchema, null, 2)}\n`;
const outputs = new Map([
  ["packages/application/schema/application-v1.json", json],
  ["apps/terminal/internal/api/application-v1.json", json],
  ["apps/terminal/internal/api/contracts_gen.go", new TextDecoder().decode(formatted.stdout)],
  [
    "packages/application/src/client-contracts.gen.ts",
    new TextDecoder().decode(tsFormatted.stdout),
  ],
]);
for (const [relative, content] of agentKitOutputs()) outputs.set(relative, content);
for (const [relative, content] of outputs) {
  const path = resolve(root, relative);
  if (process.argv.includes("--check")) {
    if (!(await Bun.file(path).exists()) || (await Bun.file(path).text()) !== content)
      throw new Error(`Generated contract is stale: ${relative}; run bun run generate:contracts`);
  } else {
    mkdirSync(dirname(path), { recursive: true });
    await Bun.write(path, content);
  }
}
// The frozen contract is a promise to people's agents: a change that breaks it fails here, in the
// landing gate, before anyone's script does (docs/reference/contract-policy.md).
const frozen = frozenContractProblems();
if (frozen.length) throw new Error(frozen.join("\n"));
console.log(
  `Application contracts ${process.argv.includes("--check") ? "verified" : "generated"}: ${outputs.size} artifacts, frozen contract honoured`,
);
