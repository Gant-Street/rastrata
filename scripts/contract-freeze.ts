/** The frozen operation contract: where the golden snapshot lives, how to read it, and whether the
 * current catalog still honours it. Used by `freeze-contract.ts` (which writes the snapshot) and by
 * `generate-application-contracts.ts` (whose gate fails the landing on a breaking change).
 * The rules are in packages/application/src/contract-compat.ts and docs/reference/contract-policy.md. */
import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import {
  compareContracts,
  viewOf,
  type Comparison,
  type ContractSnapshot,
  type ContractView,
} from "../packages/application/src/contract-compat.ts";
import {
  APPLICATION_API_VERSION,
  CORE_PREPARED_PERMISSIONS,
  PREPARED_OPERATION_PERMISSIONS,
  definitions,
  operationCatalog,
} from "../packages/application/src/schema.ts";

export const root = resolve(import.meta.dir, "..");
/** One copy for the service's tests and one the Go client embeds; they must be byte-identical. */
export const GOLDEN_FILES = [
  "packages/application/schema/contract-v1.golden.json",
  "apps/terminal/internal/api/contract-v1.golden.json",
] as const;
export const GOLDEN_NOTE =
  "The frozen operation contract. Generated by scripts/freeze-contract.ts; never edit by hand. See docs/reference/contract-policy.md.";

/** The permission needed to commit each kind of plan, limited to the kinds in `kinds`. */
export function preparedFor(kinds: Iterable<string>): Record<string, string> {
  const picked: Record<string, string> = {};
  for (const kind of kinds)
    if (PREPARED_OPERATION_PERMISSIONS[kind])
      picked[kind] = PREPARED_OPERATION_PERMISSIONS[kind] as string;
  return picked;
}

/** The view of the current catalog for `names` and the plan kinds `kinds`. */
export function currentView(names: ReadonlySet<string>, kinds: Iterable<string>): ContractView {
  return viewOf(
    APPLICATION_API_VERSION,
    operationCatalog,
    definitions,
    preparedFor(kinds) as ContractView["preparedPermissions"],
    names,
  );
}

/** The operations the program started with, which agents have been qualified on (the 24 of the
 * 2026-10-01 qualification record), and the agent lane's own token operations. They are the first
 * contract to freeze. Everything a lane added since is a preview until it is promoted
 * (docs/reference/contract-policy.md). Their present shape is the baseline; they may keep growing,
 * compatibly. */
const FIRST_FROZEN = [
  "book.get",
  "book.setup",
  "capabilities.get",
  "accounts.list",
  "accounts.prepareCreate",
  "accounts.prepareChange",
  "sources.get",
  "sources.list",
  "drafts.list",
  "drafts.get",
  "drafts.create",
  "drafts.save",
  "drafts.recover",
  "drafts.discard",
  "journal.prepare",
  "journal.list",
  "journal.get",
  "journal.prepareReverse",
  "reports.get",
  "activity.get",
  "periods.list",
  "periods.prepare",
  "operations.get",
  "operations.commit",
  "tokens.create",
  "tokens.list",
  "tokens.revoke",
  "tokens.activity",
] as const;

export function initialFrozenOperations(): Set<string> {
  const catalog = new Set(operationCatalog.map((operation) => operation.name));
  const missing = FIRST_FROZEN.filter((name) => !catalog.has(name));
  if (missing.length)
    throw new Error(`The first frozen operations are missing: ${missing.join(", ")}`);
  return new Set(FIRST_FROZEN);
}

export const initialFrozenKinds = (): string[] => Object.keys(CORE_PREPARED_PERMISSIONS);

export function readGolden(file: string = GOLDEN_FILES[0]): ContractSnapshot | null {
  const path = resolve(root, file);
  return existsSync(path) ? (JSON.parse(readFileSync(path, "utf8")) as ContractSnapshot) : null;
}

export function describeFindings(comparison: Comparison): string[] {
  return comparison.breaking.map(
    (finding) =>
      `${finding.operation}${finding.path ? ` ${finding.path}` : ""}: ${finding.message}`,
  );
}

/** What is wrong between the golden snapshot and the current catalog; empty when all is well. */
export function frozenContractProblems(): string[] {
  const golden = readGolden();
  if (!golden) return [`${GOLDEN_FILES[0]} is missing; run bun scripts/freeze-contract.ts --init`];
  const problems: string[] = [];
  const copies = GOLDEN_FILES.map((file) => {
    const path = resolve(root, file);
    return existsSync(path) ? readFileSync(path, "utf8") : null;
  });
  if (copies.some((copy) => copy === null) || new Set(copies).size !== 1)
    problems.push(
      `the two copies of the golden snapshot differ or are missing (${GOLDEN_FILES.join(", ")}); only bun scripts/freeze-contract.ts writes them`,
    );
  const comparison = compareContracts(
    golden,
    currentView(new Set(Object.keys(golden.operations)), Object.keys(golden.preparedPermissions)),
  );
  if (comparison.breaking.length)
    problems.push(
      "the frozen contract is no longer honoured:",
      ...describeFindings(comparison).map((line) => `  - ${line}`),
      "A breaking change needs a new contract version, which main decides (docs/reference/contract-policy.md). If the change is additive, say what you changed so the rule can be fixed; if it is deliberate, message main.",
    );
  return problems;
}
