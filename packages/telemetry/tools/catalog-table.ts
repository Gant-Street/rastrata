// The catalog as the markdown tables in docs/reference/telemetry.md, so the document cannot drift
// from the code. Run it with
//   bun packages/telemetry/tools/catalog-table.ts            print the tables
//   bun packages/telemetry/tools/catalog-table.ts --write    replace the block between the markers in the document
// test/docs.test.ts fails when the document's block is not what this prints.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import {
  METRIC_NAMES,
  METRICS,
  SPAN_ATTRIBUTE_KEYS,
  SPAN_EVENT_NAMES,
  SPAN_NAMES,
  exportedLabelKeys,
  prometheusName,
  worstCaseSeries,
  type MetricSpec,
} from "../src/catalog.ts";

export const START =
  "<!-- catalog:start (generated by packages/telemetry/tools/catalog-table.ts) -->";
export const END = "<!-- catalog:end -->";
export const DOCUMENT = resolve(import.meta.dir, "../../../docs/reference/telemetry.md");

const pipeSafe = (text: string) => text.replaceAll("|", "\\|");

export function catalogMarkdown(): string {
  const lines: string[] = [];
  lines.push(
    "| Key | Prometheus name | Kind | Unit | Labels (values) | Tier | Series | What it measures |",
    "| --- | --- | --- | --- | --- | --- | --- | --- |",
  );
  for (const name of METRIC_NAMES) {
    const spec = METRICS[name] as MetricSpec;
    const labels = Object.entries(spec.labels)
      .map(([key, values]) => `\`${key}\` (${(values as readonly string[]).length})`)
      .join(", ");
    const derived = exportedLabelKeys(name).filter((key) => !(key in spec.labels));
    const extra = derived.length
      ? `; derived: ${derived.map((key) => `\`${key}\``).join(", ")}`
      : "";
    lines.push(
      `| \`${name}\` | \`${prometheusName(name)}\` | ${spec.kind} | \`${spec.unit}\` | ${labels || "none"}${extra} | ${spec.tier} | ${worstCaseSeries(name)} | ${pipeSafe(spec.description)} |`,
    );
  }
  lines.push("");
  lines.push(`Span names: ${SPAN_NAMES.map((name) => `\`${name}\``).join(", ")}.`);
  lines.push("");
  lines.push(
    `Span attribute keys: ${SPAN_ATTRIBUTE_KEYS.map((key) => `\`${key}\``).join(", ")}, and any key spelled \`x.<anything>\`.`,
  );
  lines.push("");
  lines.push(
    `Span event names: ${SPAN_EVENT_NAMES.map((name) => `\`${name}\``).join(", ")}, and any name spelled \`x.<anything>\`.`,
  );
  return lines.join("\n");
}

if (import.meta.main) {
  const table = catalogMarkdown();
  if (process.argv.includes("--write")) {
    const text = readFileSync(DOCUMENT, "utf8");
    const from = text.indexOf(START);
    const to = text.indexOf(END);
    if (from < 0 || to < from) throw new Error(`${DOCUMENT} has no ${START} ... ${END} block`);
    writeFileSync(
      DOCUMENT,
      `${text.slice(0, from + START.length)}\n\n${table}\n\n${text.slice(to)}`,
    );
    console.log(`updated ${DOCUMENT}`);
  } else console.log(table);
}
