import type { StarterKind } from "./accounts.ts";

/** The starter list: common US small-business merchants, and a few things banks themselves write,
 * each with the kind of category it usually is. It is data: nothing here is fetched, learned or
 * changed at run time, and a book's own rules and history always come before it (see proposer.ts).
 *
 * A row is `[name, what the bank writes, options]`.
 *
 * - The name is how the reason says it: "USPS is usually postage."
 * - What the bank writes is one or more spellings separated by `|`, in any case and punctuation; each
 *   is looked for as whole words in the line as text.ts reads it. `a + b` needs both, anywhere in the
 *   line ("stripe + transfer" is STRIPE TRANSFER and also STRIPE DES:TRANSFER).
 * - `first`: the name must lead the line, after the words a bank puts in front (POS DEBIT, CHECKCARD
 *   1002, PAYPAL *). It is for names that are also ordinary words or places: SHELL OIL 5744 is fuel,
 *   ACE HARDWARE SHELL LAKE WI is not.
 * - `not`: spellings that rule the line out.
 * - `why`: the whole reason, where "<name> is usually <kind>." would not be a sentence.
 *
 * The rule for adding a row is precision before reach: a wrong suggestion costs trust, a missing one
 * costs a click. So a merchant that is several things is not here at all (Amazon, Costco, Walmart,
 * Target, Apple, a bare Google or Intuit), health and life insurers are not here (Schedule C's
 * insurance line is "other than health"), nothing that is usually personal is here (streaming, tax
 * preparation), and money coming in is only ever a payout from Stripe. Where a longer spelling means
 * something else it is listed too, and the longer one wins: UBER EATS is meals, UBER is travel.
 * A group with no kind is the list saying "known, and left alone on purpose": a payroll provider's
 * own fee is not payroll. */

export interface RowOptions {
  readonly first?: true;
  readonly not?: string;
  readonly why?: string;
}

export type MerchantRow = readonly [name: string, match: string, options?: RowOptions];

export interface MerchantGroup {
  readonly kind: StarterKind | null;
  readonly rows: readonly MerchantRow[];
}

const tax = (provider: string): RowOptions => ({
  why: `A tax debit from ${provider} is usually payroll taxes.`,
});

