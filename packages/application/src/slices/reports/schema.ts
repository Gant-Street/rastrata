import type { SliceSchema } from "../types.ts";

const basis = ref("ReportBasis");
const count: Schema = { type: "integer", minimum: 0 };
const boolean: Schema = { type: "boolean" };
/** A share of income: a percentage with exactly one decimal place, written as text like money ("30.2",
 * "-29.4", "100.0"). It is worked out from integers and is never a number a client should parse. */
const sharePercent: Schema = { type: "string", pattern: "^-?(0|[1-9][0-9]*)\\.[0-9]$" };

/** The honest-statements contract: every statement is a pure function of one book revision, a date
 * range, the book's basis and (for the cash-flow statement) the account tags in force. Each carries
 * the population hash of exactly those inputs, so a figure can be reproduced and drilled into. Money
 * is a decimal string with two places; nothing here is a number a client may parse. */
const definitions: Readonly<Record<string, Schema>> = {
  ReportBasis: { type: "string", enum: ["accrual", "cash"] },
  ReportComparisonKind: { type: "string", enum: ["none", "previousPeriod", "previousYear"] },
  /** What a profit and loss line may also be shown as: nothing more (the default), or its share of the
   * statement's total income. */
  ReportShare: { type: "string", enum: ["none", "income"] },
  ReportsInput: object(
    {
      asOf: date,
      from: date,
      revision,
      basis,
      compare: ref("ReportComparisonKind"),
      share: ref("ReportShare"),
    },
    ["asOf"],
  ),
  ReportWarning: object({ code: text(80), message: text(1000) }),
  FiscalYear: object({
    year: { type: "integer", minimum: 1, maximum: 9999 },
    startsOn: date,
    endsOn: date,
  }),
  ReportComparison: object({
    kind: { type: "string", enum: ["previousPeriod", "previousYear"] },
    periodStart: date,
    asOf: date,
    populationHash: hash,
  }),
  ReportRow: object({
    accountId: id,
    code: id,
    name: text(120),
    role,
    signedBalance: signedMoney,
    debit: signedMoney,
    credit: signedMoney,
  }),
  /** `share` and `comparativeShare` are on the profit and loss only, and only when the request asked for
   * `share: "income"` and the period (or its comparison) has income greater than zero: the line's
   * amount (or comparison) as a percentage of that period's total income, to one decimal, a tie
   * going away from zero. */
  StatementRow: object(
    {
      accountId: id,
      code: id,
      name: text(120),
      role,
      amount: signedMoney,
      comparative: signedMoney,
      change: signedMoney,
      share: sharePercent,
      comparativeShare: sharePercent,
    },
    ["accountId", "code", "name", "role", "amount"],
  ),
  StatementTotal: object(
    {
      key: text(40),
      label: text(120),
      amount: signedMoney,
      comparative: signedMoney,
      change: signedMoney,
      share: sharePercent,
      comparativeShare: sharePercent,
    },
    ["key", "label", "amount"],
  ),
  TrialBalanceEarnings: object({
    label: text(120),
    signedBalance: signedMoney,
    debit: signedMoney,
    credit: signedMoney,
  }),
  TrialBalance: object({
    rows: array(ref("ReportRow")),
    debit: signedMoney,
    credit: signedMoney,
    balanced: boolean,
    fiscalYearStart: date,
    retainedEarnings: nullable(ref("TrialBalanceEarnings")),
  }),
  ProfitLoss: object({
    rows: array(ref("StatementRow")),
    revenue: signedMoney,
    expenses: signedMoney,
    netIncome: signedMoney,
    totals: array(ref("StatementTotal"), 16),
  }),
  BalanceSheet: object({
    rows: array(ref("StatementRow")),
    assets: signedMoney,
    liabilities: signedMoney,
    equity: signedMoney,
    currentEarnings: signedMoney,
    balanced: boolean,
    contributedEquity: signedMoney,
    priorEarnings: signedMoney,
    difference: signedMoney,
    totals: array(ref("StatementTotal"), 16),
  }),
  CoreReports: object({
    compilerVersion: text(80),
    populationHash: hash,
    bookRevision: revision,
    postingSequence: revision,
    asOf: date,
    periodStart: date,
    currency: text(3),
    basis,
    fiscalYear: ref("FiscalYear"),
    trialBalance: ref("TrialBalance"),
    profitAndLoss: ref("ProfitLoss"),
    balanceSheet: ref("BalanceSheet"),
    comparison: nullable(ref("ReportComparison")),
    warnings: array(ref("ReportWarning"), 16),
  }),

  CashFlowInput: object(
    {
      asOf: date,
      from: date,
      revision,
      basis,
      compare: ref("ReportComparisonKind"),
      tagsRevision: revision,
    },
    ["asOf"],
  ),
  CashFlowLine: object(
    {
      key: text(80),
      group: { type: "string", enum: ["netIncome", "nonCash", "workingCapital", "account"] },
      label: text(200),
      code: nullable(id),
      accountId: nullable(id),
      amount: signedMoney,
      comparative: signedMoney,
      change: signedMoney,
    },
    ["key", "group", "label", "code", "accountId", "amount"],
  ),
  CashFlowSection: object(
    {
      key: { type: "string", enum: ["operating", "investing", "financing", "unclassified"] },
      label: text(120),
      lines: array(ref("CashFlowLine")),
      total: signedMoney,
      comparative: signedMoney,
      change: signedMoney,
    },
    ["key", "label", "lines", "total"],
  ),
  CashAccount: object({
    accountId: id,
    code: id,
    name: text(120),
    opening: signedMoney,
    closing: signedMoney,
    change: signedMoney,
  }),
  CashFlow: object({
    compilerVersion: text(80),
    populationHash: hash,
    ledgerPopulationHash: hash,
    tagMapHash: hash,
    tagsRevision: revision,
    bookRevision: revision,
    postingSequence: revision,
    asOf: date,
    periodStart: date,
    currency: text(3),
    basis,
    fiscalYear: ref("FiscalYear"),
    available: boolean,
    reason: nullable(text(1000)),
    sections: array(ref("CashFlowSection"), 4),
    cashAccounts: array(ref("CashAccount")),
    openingCash: nullable(signedMoney),
    netChange: nullable(signedMoney),
    closingCash: nullable(signedMoney),
    ties: nullable(boolean),
    totals: array(ref("StatementTotal"), 8),
    comparison: nullable(ref("ReportComparison")),
    warnings: array(ref("ReportWarning"), 16),
  }),

  BalanceKind: { type: "string", enum: ["cumulative", "fiscalYearToDate"] },
  GeneralLedgerInput: object({ asOf: date, from: date, revision, basis, page }, ["asOf"]),
  GeneralLedgerAccount: object({
    accountId: id,
    code: id,
    name: text(120),
    role,
    balanceKind: ref("BalanceKind"),
    openingBalance: signedMoney,
    totalDebit: signedMoney,
    totalCredit: signedMoney,
    netChange: signedMoney,
    closingBalance: signedMoney,
    lineCount: count,
  }),
  GeneralLedgerLine: object(
    {
      accountId: id,
      journalId: id,
      postingId: id,
      date,
      narration: text(1000),
      /** The entry's number in the book ("No. 23"). */
      postingSequence: revision,
      debit: signedMoney,
      credit: signedMoney,
      runningBalance: signedMoney,
    },
    [
      "accountId",
      "journalId",
      "postingId",
      "date",
      "narration",
      "debit",
      "credit",
      "runningBalance",
    ],
  ),
  GeneralLedger: object({
    compilerVersion: text(80),
    populationHash: hash,
    bookRevision: revision,
    postingSequence: revision,
    asOf: date,
    periodStart: date,
    currency: text(3),
    basis,
    fiscalYear: ref("FiscalYear"),
    accounts: array(ref("GeneralLedgerAccount")),
    count,
    page,
    pageSize: { type: "integer", minimum: 1 },
    lines: array(ref("GeneralLedgerLine"), 100),
  }),

  /** What a ranking of entries ranks: the money the book spent (expense accounts) or took in (income accounts). */
  LargestKind: { type: "string", enum: ["expense", "income"] },
  LargestInput: object(
    {
      asOf: date,
      from: date,
      revision,
      kind: ref("LargestKind"),
      limit: { type: "integer", minimum: 1, maximum: 50 },
    },
    ["asOf"],
  ),
  LargestRow: object({
    rank: { type: "integer", minimum: 1, maximum: 50 },
    journalId: id,
    date,
    narration: text(1000),
    /** The entry's number in the book ("No. 23"). */
    postingSequence: revision,
    /** The account that holds the largest part of the amount, and how many accounts the amount is spread over (more than one for a
     * split entry). */
    accountId: id,
    code: id,
    name: text(120),
    accounts: { type: "integer", minimum: 1 },
    amount: money,
  }),
  Largest: object({
    bookRevision: revision,
    postingSequence: revision,
    asOf: date,
    periodStart: date,
    currency: text(3),
    kind: ref("LargestKind"),
    limit: { type: "integer", minimum: 1, maximum: 50 },
    /** How many entries were ranked: all of that kind in the range, not only the rows returned. */
    count,
    rows: array(ref("LargestRow"), 50),
  }),

  ActivityInput: object(
    {
      accountId: id,
      asOf: date,
      revision,
      /** Omitted: the lines are read as the book stands, and the reply names the population to pass for the
       * next page. */
      populationHash: hash,
      from: date,
      to: date,
      page,
      reportFrom: date,
    },
    ["accountId", "asOf", "from", "to"],
  ),
  ActivityAccount: object({
    id,
    code: id,
    name: text(120),
    role,
    normalSide: { type: "string", enum: ["debit", "credit"] },
  }),
  ActivityRow: object(
    {
      journalId: id,
      postingId: id,
      date,
      narration: text(1000),
      /** The entry's number in the book ("No. 23"). */
      postingSequence: revision,
      debit: signedMoney,
      credit: signedMoney,
      runningBalance: signedMoney,
    },
    ["journalId", "postingId", "date", "narration", "debit", "credit", "runningBalance"],
  ),
  AccountActivity: object({
    account: ref("ActivityAccount"),
    currency: text(3),
    basis,
    asOf: date,
    from: date,
    to: date,
    reportFrom: date,
    revision,
    populationHash: hash,
    balanceKind: ref("BalanceKind"),
    openingBalance: signedMoney,
    closingBalance: signedMoney,
    totalDebit: signedMoney,
    totalCredit: signedMoney,
    netChange: signedMoney,
    count,
    page,
    pageSize: { type: "integer", minimum: 1 },
    rows: array(ref("ActivityRow"), 25),
  }),

  ReportStatement: {
    type: "string",
    enum: ["trial-balance", "profit-loss", "balance-sheet", "cash-flow", "general-ledger"],
  },
  ReportExportInput: object(
    {
      statement: ref("ReportStatement"),
      asOf: date,
      from: date,
      revision,
      basis,
      compare: ref("ReportComparisonKind"),
      tagsRevision: revision,
      /** For the general ledger only: the one account whose lines the file holds (an account register).
       * Without it the file holds every account. */
      accountId: id,
      /** For the profit and loss only: add each line's share of total income (and the comparison's). */
      share: ref("ReportShare"),
    },
    ["statement", "asOf"],
  ),
  ReportExport: object({
    statement: ref("ReportStatement"),
    filename: text(200),
    mediaType: text(80),
    bookRevision: revision,
    populationHash: hash,
    content: { type: "string", maxLength: 16_000_000 },
  }),
  ReportCalendar: object({
    currency: text(3),
    basis,
    bookRevision: revision,
    firstDate: date,
    lastDate: date,
    latestPostingDate: nullable(date),
    fiscalYears: array(ref("FiscalYear")),
  }),
};

