import {
  array,
  hash,
  id,
  nullable,
  object,
  operation,
  ref,
  signedMoney,
  text,
  type Schema,
} from "../../schema-kit.ts";
import type { SliceSchema } from "../types.ts";

/** UTC instant, always written by this program, for example 2026-10-03T18:15:00.000Z. */
const instant: Schema = {
  type: "string",
  pattern: "^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}(\\.[0-9]{1,6})?Z$",
  maxLength: 40,
};
const count: Schema = { type: "integer", minimum: 0 };
const flag: Schema = { type: "boolean" };
const bounded = (minimum: number, maximum: number): Schema => ({
  type: "integer",
  minimum,
  maximum,
});
const choice = (...values: string[]): Schema => ({ type: "string", enum: values });
/** A path on the machine running the service, for display. Never an input. */
const location = text(1024);

/** The safety slice: backups, restore drills and the open export. Everything that touches the
 * file system or SQLite is done by the local runtime behind a host port; see slices/safety/. */
export const safetySchema: SliceSchema = {
  name: "safety",
  definitions: {
    BackupSettings: object({
      enabled: flag,
      intervalHours: bounded(1, 720),
      onShutdown: flag,
      verifyAfterBackup: flag,
      keepDaily: bounded(1, 365),
      keepWeekly: bounded(0, 520),
      keepMonthly: bounded(0, 240),
      warnAfterHours: bounded(1, 8760),
    }),
    BackupVerificationSummary: object({
      verifiedAt: instant,
      passed: flag,
      durationMs: count,
      replayMs: nullable(count),
      checks: array(ref("BackupCheck"), 60),
    }),
    BackupRecord: object({
      id,
      createdAt: instant,
      reason: choice("manual", "scheduled", "startup", "shutdown"),
      fileName: text(255),
      bytes: count,
      sha256: hash,
      head: ref("LedgerHead"),
      bookName: text(200),
      currency: text(3),
      release: text(40),
      schemaVersion: text(400),
      fileState: choice("present", "missing"),
      verification: nullable(ref("BackupVerificationSummary")),
    }),
    BackupCheck: object({
      code: text(60),
      status: choice("passed", "failed", "skipped"),
      message: text(600),
    }),
    BackupTargetInput: object({ backupId: id }, []),
    BackupVerification: object({
      backupId: id,
      verifiedAt: instant,
      passed: flag,
      durationMs: count,
      replayMs: nullable(count),
      outcomes: count,
      journals: count,
      head: nullable(ref("LedgerHead")),
      checks: array(ref("BackupCheck"), 60),
    }),
    BackupMismatch: object({ accountId: id, live: signedMoney, restored: signedMoney }),
    BackupDrillResult: object({
      backupId: id,
      ranAt: instant,
      passed: flag,
      durationMs: count,
      replayMs: nullable(count),
      restoredHead: nullable(ref("LedgerHead")),
      liveHead: ref("LedgerHead"),
      changesSince: nullable(count),
      accountsCompared: count,
      mismatches: array(ref("BackupMismatch"), 200),
      checks: array(ref("BackupCheck"), 60),
    }),
    BackupList: object({
      directory: location,
      backups: array(ref("BackupRecord"), 5000),
      unrecorded: array(text(255), 200),
    }),
    BackupAutomaticState: object({
      enabled: flag,
      scheduler: choice("active", "off", "not_running"),
      lastRunAt: nullable(instant),
      lastRunOk: nullable(flag),
      lastError: nullable(text(600)),
      nextRunAt: nullable(instant),
    }),
    BackupJobState: object({
      kind: choice("backup", "verify", "drill", "export"),
      startedAt: instant,
      stage: text(200),
      done: nullable(count),
      total: nullable(count),
      elapsedMs: count,
      remainingMs: nullable(count),
    }),
    BackupWarning: object({
      code: text(60),
      tone: choice("info", "review", "error"),
      message: text(600),
    }),
    BackupStatus: object({
      generatedAt: instant,
      directory: location,
      settings: ref("BackupSettings"),
      automatic: ref("BackupAutomaticState"),
      activeJob: nullable(ref("BackupJobState")),
      liveHead: ref("LedgerHead"),
      latest: nullable(ref("BackupRecord")),
      latestVerified: nullable(ref("BackupRecord")),
      lastDrill: nullable(ref("BackupDrillResult")),
      changesSinceLatest: nullable(count),
      backupCount: count,
      warnings: array(ref("BackupWarning"), 20),
    }),
    ExportCreateInput: object({ format: choice("directory") }, []),
    ExportFileInfo: object({
      path: text(255),
      bytes: count,
      sha256: hash,
      lines: nullable(count),
    }),
    ExportCounts: object({
      journals: count,
      postings: count,
      accounts: count,
      commands: count,
      sources: count,
    }),
    ExportRecord: object({
      id,
      createdAt: instant,
      format: text(40),
      location,
      head: ref("LedgerHead"),
      counts: ref("ExportCounts"),
      bytes: count,
      files: array(ref("ExportFileInfo"), 50),
      manifestSha256: hash,
    }),
    ExportList: object({
      directory: location,
      exports: array(ref("ExportRecord"), 1000),
    }),
    BackupJobError: object({ code: text(60), message: text(600) }),
    /** What a long operation returns: a backup, a verification, a restore drill or an export may
     * take longer than a request should wait, so each answers with the job. While `state` is
     * `running`, ask again with the same operationId (or read backup.status) until it is `done`
     * or `failed`; the result is in the member named after the kind. */
    BackupJob: object(
      {
        state: choice("running", "done", "failed"),
        kind: choice("backup", "verify", "drill", "export"),
        startedAt: instant,
        finishedAt: instant,
        stage: text(200),
        done: nullable(count),
        total: nullable(count),
        elapsedMs: count,
        remainingMs: nullable(count),
        error: ref("BackupJobError"),
        backup: ref("BackupRecord"),
        verification: ref("BackupVerification"),
        drill: ref("BackupDrillResult"),
        export: ref("ExportRecord"),
      },
      ["state", "kind", "startedAt", "stage", "done", "total", "elapsedMs", "remainingMs"],
    ),
  },
  operations: [
    operation(
      "backup.status",
      "Summarize the safety of the book: the newest backup, the newest verified backup, the last restore drill, automatic backup state, any job running now and plain warnings (never backed up, never verified, stale, failed). Read this before closing a period or making a large change.",
      "read",
      "Empty",
      false,
      "BackupStatus",
    ),
    operation(
      "backup.list",
      "List recorded backups, newest first, with their ledger head, size and latest verification. Files in the backup folder that are not recorded backups are listed by name.",
      "read",
      "Empty",
      false,
      "BackupList",
    ),
    operation(
      "backup.create",
      "Take a consistent snapshot of the whole local database (ledger and product state) into the backup folder and record its manifest: time, ledger head and chain hash, schema version and SHA-256. Returns a job: if state is running, ask again with the same operationId. Every call makes a new backup. A new backup is not trusted until backup.verify has passed on it.",
      "configure",
      "Empty",
      true,
      "BackupJob",
    ),
    operation(
      "backup.verify",
      "Verify a backup (the newest unless backupId is given) on a copy: file size and SHA-256 against its manifest, the SQLite integrity check, the ledger chain, and a full replay of every command compared with the manifest head. The replay takes about a second for every thousand entries of a book made by this version, and grows with the square of the book for one made by an earlier version (about 22 seconds at 1,000 journals, minutes at several thousand). Returns a job: while state is running, ask again with the same operationId. The result is recorded next to the backup.",
      "configure",
      "BackupTargetInput",
      true,
      "BackupJob",
    ),
    operation(
      "backup.drill",
      "Run a restore drill with the newest backup (or backupId): restore it into a temporary directory exactly as an offline restore would, replay its ledger, then compare its head, its chain and every account balance with the live book at the same point, and discard the copy. The live book is never changed. Takes as long as a verification. Returns a job: while state is running, ask again with the same operationId. Pass or fail is recorded.",
      "configure",
      "BackupTargetInput",
      true,
      "BackupJob",
    ),
    operation(
      "backup.configure",
      "Replace the automatic backup settings: whether they run, how often, whether a backup is taken on shutdown, whether each one is verified, how many daily, weekly and monthly backups are kept, and after how many hours without a verified backup the book warns. Lowering what is kept deletes older automatic backups at the next clean-up. Manual backups are never deleted automatically. Owner only.",
      "provision",
      "BackupSettings",
      true,
      "BackupSettings",
    ),
    operation(
      "export.create",
      "Write the open export (rastrata-export-v1) into the export folder: a README describing the format, a manifest with SHA-256 hashes, book.json, journals.jsonl, chart.csv, general-ledger.csv, trial-balance.csv, sources.jsonl and commands.jsonl (the sealed commands that rebuild an identical book by replay). Spreadsheet formulas in text are neutralised in the CSV files. Returns a job: while state is running, ask again with the same operationId.",
      "configure",
      "ExportCreateInput",
      true,
      "BackupJob",
    ),
    operation(
      "export.list",
      "List the exports in the export folder, newest first, with their ledger head, counts and file hashes.",
      "read",
      "Empty",
      false,
      "ExportList",
    ),
  ],
};
