function activatedBook(profile?: BookExecutionProfile): { state: BookState; protocol: ReturnType<typeof createBookProtocolState> } {
  const base = createBookState(
    identity,
    periods,
    {
      bookId: IDS.book,
      functionalCommodityId: IDS.usd,
      accounts: [
        {
          id: IDS.cash,
          bookId: IDS.book,
          code: "1000",
          name: "Cash",
          role: "asset",
          normalSide: "debit",
          postingAllowed: true,
          openedOn: localDate("2020-01-01"),
          allowedCommodityIds: [],
        },
        {
          id: IDS.revenue,
          bookId: IDS.book,
          code: "4000",
          name: "Revenue",
          role: "income",
          normalSide: "credit",
          postingAllowed: true,
          openedOn: localDate("2020-01-01"),
          allowedCommodityIds: [],
        },
      ],
      dimensions: [],
      dimensionMembers: [],
      requiredDimensionIds: [],
    },
    [policy],
    [quantizationPolicy],
    testPolicies,
    instant("2020-01-01T00:00:00Z"),
    profile,
  );
  const protocol = createBookProtocolState();
  const active = executeBookCommand(base, protocol, activationCommand());
  if (active.result.disposition !== "committed") throw new Error("Failed to activate");
  return { state: active.state, protocol: active.protocol };
}

function makeJournal(jId: string, p1Id: string, p2Id: string, amount: string): JournalTransaction {
  return Object.freeze({
    id: journalId(jId),
    kind: "ordinary",
    bookId: IDS.book,
    functionalCommodityId: IDS.usd,
    economicAt: instant("2026-01-15T12:00:00Z"),
    accountingDate: localDate("2026-01-15"),
    recordedAt: instant("2026-01-15T12:00:00Z"),
    narration: `Journal ${jId}`,
    postings: Object.freeze([
      Object.freeze({
        id: postingId(p1Id),
        ordinal: 1n,
        accountId: IDS.cash,
        units: Object.freeze({ canonicalNumber: ExactRational.of(10n, 1n), commodityId: IDS.usd }),
        bookValue: Object.freeze({ amount: ExactDecimal.parse(amount), functionalCommodityId: IDS.usd }),
        dimensionMemberIds: Object.freeze([]),
      }),
      Object.freeze({
        id: postingId(p2Id),
        ordinal: 2n,
        accountId: IDS.revenue,
        units: Object.freeze({ canonicalNumber: ExactRational.of(-10n, 1n), commodityId: IDS.usd }),
        bookValue: Object.freeze({ amount: ExactDecimal.parse(amount).negate(), functionalCommodityId: IDS.usd }),
        dimensionMemberIds: Object.freeze([]),
      }),
    ]),
  });
}

function setupCollidingState(profile?: BookExecutionProfile) {
  const { state, protocol } = activatedBook(profile);

  // Both effect keys are generated by actual admitted commands. No journal,
  // revision, effect key or state hash is patched after publication.
  const journalA = makeJournal("j", "pA1", "pA2", "100.00");
  const postA = sealCommand({
    id: commandId("1:2"),
    type: "postJournal" as const,
    bookId: IDS.book,
    actorId: IDS.actor,
    protocolVersion: semanticVersion("1.0.0"),
    expectedBookRevision: state.bookRevision,
    issuedAt: instant("2026-01-15T13:00:00Z"),
    completedAt: instant("2026-01-15T13:00:01Z"),
    committedAt: instant("2026-01-15T13:00:02Z"),
    resolved: resolved(journalA),
  });
  const resA = executeBookCommand(state, protocol, postA);
  expect(resA.result.disposition).toBe("committed");

  const journalB = makeJournal("j:1", "pB1", "pB2", "200.00");
  const postB = sealCommand({
    id: commandId("2"),
    type: "postJournal" as const,
    bookId: IDS.book,
    actorId: IDS.actor,
    protocolVersion: semanticVersion("1.0.0"),
    expectedBookRevision: resA.state.bookRevision,
    issuedAt: instant("2026-01-15T13:01:00Z"),
    completedAt: instant("2026-01-15T13:01:01Z"),
    committedAt: instant("2026-01-15T13:01:02Z"),
    resolved: resolved(journalB),
  });
  const resB = executeBookCommand(resA.state, resA.protocol, postB);
  expect(resB.result.disposition).toBe("committed");

  const collidingState = resB.state;
  const collidingBookedA = collidingState.journals[0]!, collidingBookedB = collidingState.journals[1]!;
  expect(`${collidingBookedA.journal.id}:${collidingBookedA.effectKey}`).toBe(`${collidingBookedB.journal.id}:${collidingBookedB.effectKey}`);
  expect(decodeDurableBook(encodeDurableBook({ state: collidingState, protocol: resB.protocol })).disposition).toBe("decoded");

  const refA = createCanonicalPostingReference(
    canonicalPostingReferenceId("ref-A"),
    IDS.book,
    journalA.id,
    collidingBookedA.journal.postings[0]!,
    effectKey(collidingBookedA.effectKey),
  );

  const refB = createCanonicalPostingReference(
    canonicalPostingReferenceId("ref-B"),
    IDS.book,
    journalB.id,
    collidingBookedB.journal.postings[0]!,
    effectKey(collidingBookedB.effectKey),
  );

  return { collidingState, protocol: resB.protocol, refA, refB, postingA: collidingBookedA.journal.postings[0]!, postingB: collidingBookedB.journal.postings[0]! };
}

test("ACC-038: structural lookup resolves delimiter collisions for allocation sources without changing legacy lookup", () => {
  const legacy = setupCollidingState(undefined);
  const structural = setupCollidingState(STRUCTURAL_SOURCE_IDENTITY_PROFILE);

  // 1. Direct resolution test: resolveCanonicalPosting across colliding tuples
  // Under legacy profile both have key "j:1:2:journal:0".
  const legacyResolvedA = resolveCanonicalPosting(legacy.collidingState, [], legacy.refA);
  expect(legacyResolvedA).toBeUndefined(); // Shadowed / collides!

  const legacyResolvedB = resolveCanonicalPosting(legacy.collidingState, [], legacy.refB);
  expect(legacyResolvedB).toBeDefined();
  expect(legacyResolvedB?.id).toBe(legacy.postingB.id);

  // The structural profile preserves the two different raw tuples.
  const structuralResolvedA = resolveCanonicalPosting(structural.collidingState, [], structural.refA);
  expect(structuralResolvedA).toBeDefined();
  expect(structuralResolvedA?.id).toBe(structural.postingA.id);

  const structuralResolvedB = resolveCanonicalPosting(structural.collidingState, [], structural.refB);
  expect(structuralResolvedB).toBeDefined();
  expect(structuralResolvedB?.id).toBe(structural.postingB.id);

  // Other source families need their own command-level fixtures; repeating a
  // resolver call cannot prove their admission and retained-history behavior.

  // 3. End-to-end command evaluation:
  // createAllocationSchedule referencing refA:
  // - Under legacy: evaluateBookCommand rejects because source posting cannot be resolved
  // - Under structural: evaluateBookCommand succeeds and prepares intent
  {
    const scheduleCommand = (state: BookState, ref: CanonicalPostingReference) =>
      sealCommand({
        id: commandId("test-sched-cmd"),
        type: "createAllocationSchedule" as const,
        bookId: IDS.book,
        actorId: IDS.actor,
        protocolVersion: semanticVersion("1.0.0"),
        expectedBookRevision: state.bookRevision,
        issuedAt: instant("2026-01-15T14:00:00Z"),
        completedAt: instant("2026-01-15T14:00:01Z"),
        committedAt: instant("2026-01-15T14:00:02Z"),
        request: {
          id: allocationScheduleId("sched-test-1"),
          policyId: allocPolicy.id,
          policyVersion: allocPolicy.version,
          startsOn: localDate("2026-01-15"),
          endsOn: localDate("2026-03-15"),
          governedAt: instant("2026-01-15T12:00:00Z"),
          source: ref,
          sourceBasis: ExactRational.of(100n, 1n),
          residualValue: ExactRational.zero(),
          derivation: accountingDerivation,
        },
      });

    const legacyEval = evaluateBookCommand(legacy.collidingState, legacy.protocol, scheduleCommand(legacy.collidingState, legacy.refA));
    expect(legacyEval.disposition).toBe("finished");
    if (legacyEval.disposition === "finished") {
      expect(legacyEval.result.disposition).toBe("rejected");
      expect(legacyEval.result.diagnostics.some((d) => d.code === "unresolved_accounting_input" && d.path.includes("source"))).toBeTrue();
      expect(legacyEval.result.diagnostics[0]?.requirementIds).toContain("ACC-038");
    }

    const structuralEval = evaluateBookCommand(structural.collidingState, structural.protocol, scheduleCommand(structural.collidingState, structural.refA));
    expect(structuralEval.disposition).toBe("ready");
    for (const [scenario, disposition] of [[legacy, "rejected"], [structural, "committed"]] as const) {
      const command = scheduleCommand(scenario.collidingState, scenario.refA);
      const result = executeBookCommand(scenario.collidingState, scenario.protocol, command);
      expect(result.result.disposition).toBe(disposition);
      expect(result.state.accountingState.allocationSchedules.map(schedule => schedule.sourceBasis.toString()))
        .toEqual(disposition === "committed" ? ["100/1"] : []);
      const bytes = encodeDurableBook({ state: result.state, protocol: result.protocol });
      const restored = decodeDurableBook(bytes);
      expect(restored.disposition).toBe("decoded");
      if (restored.disposition !== "decoded") throw new Error(restored.message);
      const replay = executeBookCommand(restored.aggregate.state, restored.aggregate.protocol, command);
      expect(replay.result).toEqual({ ...result.result, disposition: "replayed" });
      expect(encodeDurableBook({ state: replay.state, protocol: replay.protocol })).toBe(bytes);
    }
  }
});
