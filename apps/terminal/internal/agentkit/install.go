// Options say what to write and where.
type Options struct {
	// Dir is the project folder. It must already exist.
	Dir    string
	Agents []Agent
	// MCP writes (or, for Codex, prints) the MCP server entry too.
	MCP    bool
	MCPURL string
	// Force replaces a file or entry that was edited, or that is not ours.
	Force  bool
	DryRun bool
}

// File is what happened to one file.
type File struct {
	Agent string `json:"agent"`
	// Path is relative to the project folder, with forward slashes.
	Path string `json:"path"`
	// Action is created, updated, unchanged or skipped (dry runs say "would create" and so on).
	Action string `json:"action"`
	Note   string `json:"note,omitempty"`
}

// Snippet is text the person adds themselves, because the file it belongs in is not in the project.
type Snippet struct {
	Agent    string `json:"agent"`
	Where    string `json:"where"`
	Language string `json:"language"`
	Text     string `json:"text"`
}

// Result is everything Init did and everything the person still has to do.
type Result struct {
	Dir       string    `json:"dir"`
	DryRun    bool      `json:"dryRun"`
	Agents    []string  `json:"agents"`
	Files     []File    `json:"files"`
	Snippets  []Snippet `json:"snippets"`
	Notes     []string  `json:"notes"`
	KitDigest string    `json:"kitDigest"`
}

const (
	fileMarker   = "<!-- generated by rastrata agent init"
	sectionBegin = "<!-- rastrata:begin"
	sectionEnd   = "<!-- rastrata:end -->"
)

func sum(text string) string {
	digest := sha256.Sum256([]byte(text))
	return hex.EncodeToString(digest[:])
}

// Init writes the kit for each agent into the project folder. It is idempotent: a second run
// changes nothing. A file that was edited since it was written, or that was never ours, is left
// alone unless Force is set.
func Init(options Options) (Result, error) {
	if options.MCPURL == "" {
		options.MCPURL = DefaultMCPURL
	}
	info, err := os.Stat(options.Dir)
	if err != nil || !info.IsDir() {
		return Result{}, fmt.Errorf("%s is not a folder; run this from your project's root or choose one with --dir", options.Dir)
	}
	if len(options.Agents) == 0 {
		return Result{}, errors.New("choose an agent: --agent claude, codex, opencode or all")
	}
	// Refuse the whole request before writing anything, so a typo in the last agent cannot leave a
	// half-written project behind.
	for _, agent := range options.Agents {
		if agent != Claude && agent != Codex && agent != OpenCode {
			return Result{}, fmt.Errorf("unknown agent %q: choose claude, codex or opencode", agent)
		}
	}
	result := Result{Dir: options.Dir, DryRun: options.DryRun, Files: []File{}, Snippets: []Snippet{}, Notes: []string{}, KitDigest: KitDigest()}
	wroteAgents := false
	for _, agent := range options.Agents {
		result.Agents = append(result.Agents, string(agent))
		switch agent {
		case Claude:
			result.Files = append(result.Files,
				writeManagedFile(options, agent, ".claude/skills/rastrata/SKILL.md", ClaudeSkill(), true),
				writeManagedFile(options, agent, ".claude/skills/rastrata/guide.md", ClaudeGuide(), false))
			if options.MCP {
				result.Files = append(result.Files, mergeEntry(options, &result, agent, ".mcp.json", "mcpServers", claudeEntry(options.MCPURL), false))
			}
		case Codex:
			if !wroteAgents {
				result.Files = append(result.Files, writeSection(options, agent, "AGENTS.md"))
				wroteAgents = true
			}
			if options.MCP {
				result.Snippets = append(result.Snippets, codexSnippet(options.MCPURL))
			}
		case OpenCode:
			if !wroteAgents {
				result.Files = append(result.Files, writeSection(options, agent, "AGENTS.md"))
				wroteAgents = true
			}
			if options.MCP {
				result.Files = append(result.Files, mergeEntry(options, &result, agent, "opencode.json", "mcp", openCodeEntry(options.MCPURL), true))
			}
		default:
			return Result{}, fmt.Errorf("unknown agent %q: choose claude, codex or opencode", agent)
		}
	}
	result.Notes = append(result.Notes,
		"Give the agent its token in the environment variable "+TokenVariable+" (create one with: rastrata tokens create --label NAME --preset draft). Do not put the token in a file in the project.",
		"Check what an agent will be able to do with: rastrata agent status")
	if options.MCP {
		result.Notes = append(result.Notes, "The MCP entry points at "+options.MCPURL+", which needs the MCP server running (bun run dev:mcp). The command line works without it.")
	}
	return result, nil
}

// ---- files ---------------------------------------------------------------------------------

func slash(path string) string { return filepath.ToSlash(path) }

func record(options Options, agent Agent, path, action, note string) File {
	if options.DryRun && (action == "created" || action == "updated") {
		action = "would be " + action
	}
	return File{Agent: string(agent), Path: slash(path), Action: action, Note: note}
}

func readIfExists(path string) (string, bool, error) {
	data, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return "", false, nil
	}
	if err != nil {
		return "", false, err
	}
	return string(data), true, nil
}

func write(options Options, relative, content string) error {
	if options.DryRun {
		return nil
	}
	full := filepath.Join(options.Dir, filepath.FromSlash(relative))
	if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
		return err
	}
	return os.WriteFile(full, []byte(content), 0o644)
}

// withMarker puts the marker line that records what the file should hold, after any frontmatter.
func withMarker(content string, frontmatter bool) string {
	head, body := "", content
	if frontmatter && strings.HasPrefix(content, "---\n") {
		if end := strings.Index(content[4:], "\n---\n"); end >= 0 {
			cut := 4 + end + len("\n---\n")
			head, body = content[:cut], content[cut:]
		}
	}
	return head + fmt.Sprintf("%s (kit %s); sha256=%s -->\n", fileMarker, KitDigest(), sum(head+body)) + body
}

// intact reports whether a file is exactly what a run of this command wrote: its marker is there
// and the rest of the file still hashes to what the marker recorded.
func intact(content string) bool {
	lines := strings.SplitAfter(content, "\n")
	for index, line := range lines {
		if !strings.HasPrefix(line, fileMarker) {
			continue
		}
		recorded := strings.TrimSuffix(strings.TrimSpace(line[strings.Index(line, "sha256=")+len("sha256="):]), "-->")
		rest := strings.Join(lines[:index], "") + strings.Join(lines[index+1:], "")
		return strings.TrimSpace(recorded) == sum(rest)
	}
	return false
}

func writeManagedFile(options Options, agent Agent, relative, content string, frontmatter bool) File {
	wanted := withMarker(content, frontmatter)
	full := filepath.Join(options.Dir, filepath.FromSlash(relative))
	existing, exists, err := readIfExists(full)
	if err != nil {
		return record(options, agent, relative, "skipped", "could not read it: "+err.Error())
	}
	if exists && existing == wanted {
		return record(options, agent, relative, "unchanged", "")
	}
	if exists && !options.Force {
		if !strings.Contains(existing, fileMarker) {
			return record(options, agent, relative, "skipped", "a file already exists here that this command did not write; use --force to replace it")
		}
		if !intact(existing) {
			return record(options, agent, relative, "skipped", "it was edited after this command wrote it; use --force to replace it")
		}
	}
	if err := write(options, relative, wanted); err != nil {
		return record(options, agent, relative, "skipped", "could not write it: "+err.Error())
	}
	if exists {
		return record(options, agent, relative, "updated", "")
	}
	return record(options, agent, relative, "created", "")
}

// writeSection puts the runbook between markers in AGENTS.md, leaving everything else as it is.
func writeSection(options Options, agent Agent, relative string) File {
	body := AgentsSection()
	section := fmt.Sprintf("%s kit=%s sha256=%s -->\n%s%s\n", sectionBegin, KitDigest(), sum(body), body, sectionEnd)
	full := filepath.Join(options.Dir, relative)
	existing, exists, err := readIfExists(full)
	if err != nil {
		return record(options, agent, relative, "skipped", "could not read it: "+err.Error())
	}
	if !exists {
		if err := write(options, relative, section); err != nil {
			return record(options, agent, relative, "skipped", "could not write it: "+err.Error())
		}
		return record(options, agent, relative, "created", "")
	}
	start := strings.Index(existing, sectionBegin)
	if start < 0 {
		// A blank line between the person's text and ours, without touching what they wrote.
		separator := ""
		switch {
		case !strings.HasSuffix(existing, "\n"):
			separator = "\n\n"
		case !strings.HasSuffix(existing, "\n\n"):
			separator = "\n"
		}
		if err := write(options, relative, existing+separator+section); err != nil {
			return record(options, agent, relative, "skipped", "could not write it: "+err.Error())
		}
		return record(options, agent, relative, "updated", "added a section; the rest of the file is untouched")
	}
	endAt := strings.Index(existing[start:], sectionEnd)
	if endAt < 0 {
		return record(options, agent, relative, "skipped", "the Rastrata section has a start marker but no end marker; fix the file or remove the section, then run this again")
	}
	endAt += start + len(sectionEnd)
	if existing[start:endAt] == strings.TrimSuffix(section, "\n") {
		return record(options, agent, relative, "unchanged", "")
	}
	current := existing[start:endAt]
	if !options.Force && !sectionIntact(current) {
		return record(options, agent, relative, "skipped", "the Rastrata section was edited after this command wrote it; use --force to replace it")
	}
	updated := existing[:start] + strings.TrimSuffix(section, "\n") + existing[endAt:]
	if err := write(options, relative, updated); err != nil {
		return record(options, agent, relative, "skipped", "could not write it: "+err.Error())
	}
	return record(options, agent, relative, "updated", "replaced the Rastrata section; the rest of the file is untouched")
}

func sectionIntact(section string) bool {
	firstLine, rest, found := strings.Cut(section, "\n")
	if !found || !strings.HasPrefix(firstLine, sectionBegin) {
		return false
	}
	at := strings.Index(firstLine, "sha256=")
	if at < 0 {
		return false
	}
	recorded := strings.TrimSpace(strings.TrimSuffix(strings.TrimSpace(firstLine[at+len("sha256="):]), "-->"))
	inner := strings.TrimSuffix(rest, sectionEnd)
	return recorded == sum(inner)
}

// ---- MCP entries ---------------------------------------------------------------------------

func claudeEntry(url string) json.RawMessage {
	return json.RawMessage(fmt.Sprintf(`{"type":"http","url":%q,"headers":{"Authorization":"Bearer ${%s}"}}`, url, TokenVariable))
}

func openCodeEntry(url string) json.RawMessage {
	return json.RawMessage(fmt.Sprintf(`{"type":"remote","url":%q,"enabled":true,"headers":{"Authorization":"Bearer {env:%s}"}}`, url, TokenVariable))
}

func codexSnippet(url string) Snippet {
	return Snippet{
		Agent:    string(Codex),
		Where:    "~/.codex/config.toml (or .codex/config.toml in a trusted project)",
		Language: "toml",
		Text:     fmt.Sprintf("[mcp_servers.%s]\nurl = %q\nbearer_token_env_var = %q\n", ServerName, url, TokenVariable),
	}
}

// entrySnippet is what to add by hand when a JSON file cannot be merged safely.
func entrySnippet(agent Agent, relative, container string, entry json.RawMessage) Snippet {
	var indented bytes.Buffer
	_ = json.Indent(&indented, []byte(fmt.Sprintf(`{%q:{%q:%s}}`, container, ServerName, entry)), "", "  ")
	return Snippet{Agent: string(agent), Where: relative, Language: "json", Text: indented.String() + "\n"}
}

// mergeEntry adds the rastrata server to a JSON configuration file, keeping everything else in it,
// in its order. A file it cannot read as plain JSON (comments, a syntax error) is not touched and
// the entry is printed instead.
func mergeEntry(options Options, result *Result, agent Agent, relative, container string, entry json.RawMessage, schema bool) File {
	full := filepath.Join(options.Dir, relative)
	existing, exists, err := readIfExists(full)
	if err != nil {
		return record(options, agent, relative, "skipped", "could not read it: "+err.Error())
	}
	top := []member{}
	if schema {
		top = append(top, member{"$schema", json.RawMessage(`"https://opencode.ai/config.json"`)})
	}
	if exists && strings.TrimSpace(existing) != "" {
		top, err = parseObject([]byte(existing))
		if err != nil {
			result.Snippets = append(result.Snippets, entrySnippet(agent, relative, container, entry))
			return record(options, agent, relative, "skipped", "it is not plain JSON ("+err.Error()+"), so it was not touched; add the entry shown below yourself")
		}
	}
	servers := []member{}
	if index := find(top, container); index >= 0 {
		servers, err = parseObject(top[index].value)
		if err != nil {
			result.Snippets = append(result.Snippets, entrySnippet(agent, relative, container, entry))
			return record(options, agent, relative, "skipped", `"`+container+`" is not an object, so the file was not touched; add the entry shown below yourself`)
		}
	}
	if index := find(servers, ServerName); index >= 0 {
		if sameJSON(servers[index].value, entry) {
			return record(options, agent, relative, "unchanged", "")
		}
		if !options.Force {
			result.Snippets = append(result.Snippets, entrySnippet(agent, relative, container, entry))
			return record(options, agent, relative, "skipped", "a different "+ServerName+" entry is already there; use --force to replace it, or compare with the entry shown below")
		}
		servers[index].value = entry
	} else {
		servers = append(servers, member{ServerName, entry})
	}
	rendered, err := renderObject(servers)
	if err != nil {
		return record(options, agent, relative, "skipped", err.Error())
	}
	if index := find(top, container); index >= 0 {
		top[index].value = rendered
	} else {
		top = append(top, member{container, rendered})
	}
	output, err := renderObject(top)
	if err != nil {
		return record(options, agent, relative, "skipped", err.Error())
	}
	if err := write(options, relative, string(output)+"\n"); err != nil {
		return record(options, agent, relative, "skipped", "could not write it: "+err.Error())
	}
	if exists {
		return record(options, agent, relative, "updated", "added the "+ServerName+" server; everything else in the file is untouched")
	}
	return record(options, agent, relative, "created", "")
}

func sameJSON(a, b json.RawMessage) bool {
	var left, right any
	if json.Unmarshal(a, &left) != nil || json.Unmarshal(b, &right) != nil {
		return false
	}
	return reflect.DeepEqual(left, right)
}
